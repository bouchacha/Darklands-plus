#!/usr/bin/env python3
"""
recomp_drv.py - static recompiler for the small run-time loaded driver images
(MGRAPHIC.EXE, MISC.EXE, *SOUND.DLC). The game loads them with DOS 4B03 (load overlay) and
calls their entry points through far pointers taken from the slot table in the image.

  python3 -I port/recomp/recomp_drv.py <out_dir> <name>=<file> [<name>=<file> ...]

Entry points: the words of the slot table (body+0x2E: first slot index, +0x30: count, +0x32: offsets) plus everything
reachable by recursive descent (calls). Code is generated by recomp16.Gen with frame 0: the
driver's CS is its load segment. LOADSEG is redefined to the driver's load segment in the
generated file.
"""
import sys, os, struct, collections
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import recomp16
from recomp16 import Gen, MD, X, JCC


def mz(path):
    d = open(path, 'rb').read()
    (magic, cblp, cp, crlc, cparhdr) = struct.unpack_from('<5H', d, 0)
    lfarlc = struct.unpack_from('<H', d, 0x18)[0]
    size = cp * 512 - (512 - cblp if cblp else 0)
    body = d[cparhdr * 16:size]
    rel = set()
    for k in range(crlc):
        off, seg = struct.unpack_from('<2H', d, lfarlc + 4 * k)
        rel.add(seg * 16 + off)
    return body, rel


def fnv1a(b):
    """identifies a driver image whatever its file is called (GOG ships renamed copies)"""
    h = 0x811c9dc5
    for c in b:
        h = ((h ^ c) * 0x01000193) & 0xffffffff
    return h


def decode(body, pc):
    try:
        return next(MD.disasm(body[pc:pc + 16], pc))
    except StopIteration:
        return None


def flow(ins):
    """(fallthrough?, [jump targets], [call targets], [table targets])"""
    m, ops = ins.mnemonic, ins.operands
    if m in JCC or m in ('loop', 'jcxz', 'loope', 'loopne'):
        return True, [ops[0].imm & 0xffff], [], []
    if m == 'jmp':
        if ops[0].type == X.X86_OP_IMM:
            return False, [ops[0].imm & 0xffff], [], []
        return False, [], [], ['table']
    if m == 'call':
        if ops[0].type == X.X86_OP_IMM:
            return True, [], [ops[0].imm & 0xffff], []
        return True, [], [], []
    if m in ('ret', 'retf', 'iret', 'ljmp', 'hlt'):
        return False, [], [], []
    return True, [], [], []


def table_targets(body, ins):
    o = ins.operands[0]
    if o.type != X.X86_OP_MEM or o.mem.segment != X.X86_REG_CS or not (o.mem.base or o.mem.index):
        return []
    t, out = o.mem.disp & 0xffff, []
    for k in range(64):
        if t + 2 * k + 2 > len(body):
            break
        v = struct.unpack_from('<H', body, t + 2 * k)[0]
        if not (0 < v < len(body)):
            break
        out.append(v)
    return out


def analyze(img, body, entries):
    # pass 1: everything reachable; call and table targets become function entries
    ents, seen, todo = set(entries), set(), list(entries)
    while todo:
        pc = todo.pop()
        while 0 <= pc < len(body) and pc not in seen:
            ins = decode(body, pc)
            if ins is None:
                break
            seen.add(pc)
            ft, js, cs, tb = flow(ins)
            todo += js
            for c in cs:
                ents.add(c); todo.append(c)
            if tb:
                for c in table_targets(body, ins):
                    ents.add(c); todo.append(c)
            if not ft:
                break
            pc += ins.size
    # pass 2: ownership, not crossing into other entries
    insns, owner, calls = {}, {}, {}
    for ent in sorted(ents):
        work = [ent]
        while work:
            pc = work.pop()
            while 0 <= pc < len(body):
                if (img, pc) in owner or (pc in ents and pc != ent):
                    break
                ins = decode(body, pc)
                if ins is None:
                    break
                insns[(img, pc)] = (ins.size, ins.mnemonic, ins.op_str, bytes(ins.bytes), 0, pc)
                owner[(img, pc)] = ent
                ft, js, cs, tb = flow(ins)
                work += js
                if cs:
                    calls[(img, pc)] = [(img, c) for c in cs]
                if not ft:
                    break
                pc += ins.size
    return insns, owner, calls, {}


class DrvGen(Gen):
    def __init__(self, img, body, rel, entries):
        self.img = img
        self.hash = fnv1a(body)
        insns, owner, calls, jts = analyze(img, body, entries)
        self.insns, self.owner, self.calls, self.jt = insns, owner, calls, jts
        self.vectors = {}
        self.relocs = {img: rel}
        self.section_of = {img: -2}
        self.base = {img: 0}
        self.funcs = collections.defaultdict(list)
        for (i, lin), ent in owner.items():
            self.funcs[(i, ent)].append(lin)
        for k in self.funcs:
            self.funcs[k].sort()
        self.entryset = set(self.funcs)
        self.jt_at = {}
        self.vec_base = 0x9c00
        self.problems = collections.Counter()
        self.extra = collections.defaultdict(set)
        for (i, lin), r in self.insns.items():
            mn = r[1]
            if not (mn in JCC or mn in ('jmp', 'loop', 'jcxz')):
                continue
            ins = next(MD.disasm(bytes(r[3]), r[5]))
            if not ins.operands or ins.operands[0].type != X.X86_OP_IMM:
                continue
            tlin = ins.operands[0].imm & 0xffff
            ow = self.owner.get((i, tlin))
            if ow is not None and ow != self.owner.get((i, lin)) and tlin != ow:
                self.extra[(i, ow)].add(tlin)
        for (i_, lin_), r_ in self.insns.items():
            if r_[1] in ('ret', 'retf', 'iret', 'jmp', 'ljmp', 'hlt'):
                continue
            t_ = lin_ + r_[0]
            ow_ = self.owner.get((i_, t_))
            if ow_ is not None and ow_ != self.owner.get((i_, lin_)) and t_ != ow_:
                self.extra[(i_, ow_)].add(t_)
        self.find_smc()
        self.extra_name = {}
        for (i, ow), ts in self.extra.items():
            for t in ts:
                self.extra_name[(i, t)] = (ow, self.fname(i, t))

    def emit(self, out_dir):
        img = self.img
        body = ['/* generated by port/recomp/recomp_drv.py - do not edit */', '#include "cpu.h"',
                '#include "strops.h"', '#include "dispatch.h"', 'extern u16 drvseg_%s;' % img,
                '#undef LOADSEG', '#define LOADSEG drvseg_%s' % img, '']
        protos, table = [], []
        for (i, ent) in sorted(self.funcs):
            protos.append('void %s(void);' % self.fname(i, ent))
            table.append((ent, self.fname(i, ent)))
            for t in sorted(self.extra.get((i, ent), ())):
                protos.append('void %s(void);' % self.fname(i, t))
                table.append((t, self.fname(i, t)))
        body += protos + ['']
        for (i, ent) in sorted(self.funcs):
            body.append(self.gen_function(i, ent))
        table.sort()
        body.append('u16 drvseg_%s;' % img)
        body.append('static const FuncEntry tab_%s[] = {\n%s\n};' % (
            img, ',\n'.join('    {0x%05x, -2, %s}' % t for t in table)))
        rs = sorted({lin + r[0] for (i, lin), r in self.insns.items() if r[1] in ('call', 'lcall')})
        body.append('static const unsigned rets_%s[] = {%s};' % (img, ', '.join('0x%x' % x for x in rs) or '0'))
        body.append('const DriverImage DRV_%s = {"%s", tab_%s, %d, rets_%s, %d, 0x%08xu};' % (img, img, img, len(table), img, len(rs), self.hash))
        open(os.path.join(out_dir, 'd_%s.c' % img), 'w').write('\n'.join(body) + '\n')
        print(img, 'functions:', len(table), dict(self.problems))


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    names = []
    seen = set()
    for a in sys.argv[2:]:
        name, path = a.split('=', 1)
        if not os.path.exists(path):
            print('skipped (no file):', name, path)
            continue
        body, rel = mz(path)
        if fnv1a(body) in seen:
            print('skipped (same image as another):', name, path)
            continue
        seen.add(fnv1a(body))
        # header: +2a paragraphs, +2c bytes, +2e first slot index, +30 slot count, +32 offsets
        first, cnt = struct.unpack_from('<2H', body, 0x2e)
        ents = set()
        for k in range(cnt):
            v = struct.unpack_from('<H', body, 0x32 + 2 * k)[0]
            if v < len(body):
                ents.add(v)
        xf = os.path.join(HERE, 'extra_entries_drv.txt')
        if os.path.exists(xf):
            for line in open(xf):
                f = line.split('#')[0].split()
                if len(f) == 2 and (f[0] == name or (f[0] == '*roland' and name.startswith('roland'))):
                    ents.add(int(f[1], 16))
        g = DrvGen(name, body, rel, sorted(ents))
        g.emit(out)
        names.append(name)
    open(os.path.join(out, 'drivers.c'), 'w').write(
        '/* generated */\n#include "cpu.h"\n#include "dispatch.h"\n' +
        ''.join('extern const DriverImage DRV_%s; extern u16 drvseg_%s;\n' % (n, n) for n in names) +
        'const DriverImage *DRIVERS[] = {%s, 0};\n' % ', '.join('&DRV_%s' % n for n in names) +
        'u16 *DRIVER_SEGS[] = {%s, 0};\n' % ', '.join('&drvseg_%s' % n for n in names))


if __name__ == '__main__':
    main()
