#!/usr/bin/env python3
"""bin2c.py OUT.c NAME=FILE ...: embed files as const byte arrays (NAME, NAME_SIZE)."""
import sys
out = ['/* generated by port/tools/bin2c.py */']
for a in sys.argv[2:]:
    name, path = a.split('=', 1)
    d = open(path, 'rb').read()
    out.append('const unsigned int %s_SIZE = %d;' % (name, len(d)))
    out.append('const unsigned char %s[] = {' % name)
    for i in range(0, len(d), 24):
        out.append(','.join(str(b) for b in d[i:i + 24]) + ',')
    out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
