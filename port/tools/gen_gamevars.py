#!/usr/bin/env python3
"""gen_gamevars.py - port/runtime/gamevars.h from the decompilation's names.

The decompiled sources name the game's variables in include/darklands/*.h
(`#define party_size D_a67e  /* number of party members */`). The port reads and writes the
same variables from native code; this makes those names its one list of addresses:

    GV_party_size  0xa67e      (DGROUP offset; g_rw(GV_party_size))

Run after changing the names: python3 -I port/tools/gen_gamevars.py
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
SRC = [os.path.join(ROOT, 'include', 'darklands', n) for n in ('game.h', 'card.h')]
OUT = os.path.join(ROOT, 'port', 'runtime', 'gamevars.h')

pat = re.compile(r'^#define\s+([a-z_][a-z_0-9]*)\s+D_([0-9a-f]{4})\b\s*(?:/\*\s*(.*?)\s*\*/)?')
fpat = re.compile(r'^#define\s+([a-z_][a-z_0-9]*)\s+sub_(root|s(\d{3}))_([0-9a-f]{4})_([0-9a-f]{4})\b\s*(?:/\*\s*(.*?)\s*\*/)?')
funcs = []
seen = {}
rows = []
# names the decompiled sources declare under these very names (a #define in the shared headers
# would rename their symbols): only here
EXTRA = []
for path in SRC:
    for line in open(path, encoding='latin1'):
        fm = fpat.match(line)
        if fm:
            fname = fm.group(1)
            if fname not in seen:
                seen[fname] = 'f'
                sect = -1 if fm.group(2) == 'root' else int(fm.group(3))
                funcs.append((fname, sect, fm.group(4), fm.group(5), fm.group(6) or ''))
            continue
        m = pat.match(line)
        if not m:
            continue
        name, addr, note = m.group(1), m.group(2), m.group(3) or ''
        if name in seen:
            if seen[name] != addr:
                sys.exit('%s: %s is D_%s here, D_%s before' % (path, name, addr, seen[name]))
            continue
        seen[name] = addr
        rows.append((name, addr, note, os.path.basename(path)))

for name, addr, note in EXTRA:
    seen[name] = addr
    rows.append((name, addr, note, 'gen_gamevars.py'))

with open(OUT, 'w') as f:
    f.write('/* gamevars.h - the game\'s variables by the decompilation\'s names (DGROUP offsets).\n'
            ' * Generated by port/tools/gen_gamevars.py from include/darklands/game.h and card.h: change\n'
            ' * the names there, not here. Read and write them with g_rb/g_rw/g_wb/g_ww (runtime/game.h),\n'
            ' * or better through mods/gamemodel.h where it has an accessor. */\n'
            '#ifndef DL_GAMEVARS_H\n#define DL_GAMEVARS_H\n\n')
    src = None
    for name, addr, note, s in rows:
        if s != src:
            f.write('/* %s */\n' % s)
            src = s
        f.write('#define GV_%-28s 0x%s%s\n' % (name, addr, ('    /* %s */' % note) if note else ''))
    f.write('\n/* the game\'s functions: GF_name is "section, segment, offset" (link address; section -1 the\n'
            ' * root), for hook_install(GF_name, fn), game_func(GF_name), ns_call(GF_name, n, ...) */\n')
    for name, sect, seg, off, note in funcs:
        f.write('#define GF_%-28s %d, 0x%s, 0x%s%s\n' % (name, sect, seg, off, ('    /* %s */' % note) if note else ''))
    f.write('\n#endif\n')
print('wrote %s: %d variables, %d functions' % (OUT, len(rows), len(funcs)))
